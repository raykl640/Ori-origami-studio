int textWidth(const std::string& text, int scale) {
    return text.empty() ? 0 : static_cast<int>(text.size()) * 6 * scale - scale;
}

int drawText(Image& img, int x, int y, const std::string& text, Color c, int scale) {
    int pen = x;
    for (char ch : text) {
        const GlyphEntry* g = findGlyph(ch);
        for (int row = 0; row < 7; ++row)
            for (int col = 0; col < 5; ++col)
                if (g->rows[row][col] == '#')
                    for (int sy = 0; sy < scale; ++sy)
                        for (int sx = 0; sx < scale; ++sx)
                            img.setPixel(pen + col * scale + sx, y + row * scale + sy, c);
        pen += 6 * scale;
    }
    return pen;
}

void drawTextCentered(Image& img, int cx, int y, const std::string& text, Color c, int scale) {
    drawText(img, cx - textWidth(text, scale) / 2, y, text, c, scale);
}

