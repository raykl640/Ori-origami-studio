const GlyphEntry* findGlyph(char ch) {
    static std::map<char, const GlyphEntry*> index;
    if (index.empty())
        for (const auto& g : kGlyphs) index[g.ch] = &g;
    auto it = index.find(ch);
    if (it != index.end()) return it->second;
    it = index.find(static_cast<char>(std::toupper(static_cast<unsigned char>(ch))));
    return it == index.end() ? index['?'] : it->second;
}

